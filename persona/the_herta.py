def build_examples_block(examples: list[tuple[str, str]]) -> str:
    """Собирает few-shot примеры в текстовый блок для системного промпта.

    Раньше примеры подмешивались как настоящие реплики user/assistant, и модель
    выдавала их за просьбы собеседника ("вы запросили TypedDict User..."), хотя тот
    ничего подобного не писал. Внутри системного промпта такой путаницы не возникает.
    """
    lines: list[str] = [FEW_SHOT_HEADER, ""]
    for user_text, assistant_text in examples:
        lines.append(f"— Собеседник: {user_text}")
        lines.append(f"— Великая Герта: {assistant_text}")
        lines.append("")
    return "\n".join(lines).strip()


